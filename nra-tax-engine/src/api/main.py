"""FastAPI surface.

Phase 6: switches the primary submission endpoint to accept a typed
:class:`IntakePayload` instead of a free-form JSON string. The OpenAPI
schema auto-generated by FastAPI now describes every intake field, so the
client can codegen its TypeScript types from ``/openapi.json``.

The legacy multipart endpoint is preserved for backwards compatibility
with the Phase-2 client; new clients should use ``/api/v1/submit``.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import List, Optional

import uvicorn
from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from src.assembly.mailing_packager import MailingPackager
from src.intake.intake_schema import IntakePayload
from src.intake.mcq_router import MCQRouter
from src.intake.ocr_parser import DocumentParser
from src.orchestrator.engine import TaxEngine

logger = logging.getLogger(__name__)


class TaxProcessResponse(BaseModel):
    """Top-level API response."""

    status: str = Field(description="'success' or 'error'.")
    tax_year: int
    federal_refund_or_owed: float = Field(
        description="Positive = owes IRS; negative = federal refund due."
    )
    ny_refund_or_owed: float = Field(
        default=0.0,
        description="NY positive = owes NY DTF; negative = NY refund.",
    )
    fica_refund_amount: float = Field(
        default=0.0, description="Total Form 843 FICA refund amount (Ssec + Medicare)."
    )
    forms_required: List[str] = Field(default_factory=list)
    completed_layers: List[str] = Field(default_factory=list)
    generated_form_outputs: List[str] = Field(
        default_factory=list,
        description="Paths to per-form filled PDFs or field-map JSONs.",
    )
    federal_packet_path: Optional[str] = None
    ny_packet_path: Optional[str] = None
    fica_packet_path: Optional[str] = None
    requires_human_review: List[str] = Field(
        default_factory=list,
        description=(
            "Reasons a CPA must review the return before filing. Non-empty "
            "when a validator or LLM confidence check flagged something. "
            "Pass force_assembly=True on a subsequent call to override after review."
        ),
    )
    narrative_sections: dict = Field(
        default_factory=dict,
        description=(
            "Plain-English narrative sections keyed by section title. "
            "Each value is a human-readable explanation of that portion of the return. "
            "Empty dict when narrative generation is not available."
        ),
    )


app = FastAPI(
    title="QuadTax NRA Tax Engine API",
    version="0.4.0",
    description=(
        "Production NRA tax return engine. Accepts intake fields and "
        "OCR'd document text; returns refund/owed amounts and paths to "
        "generated forms and Pub-519-Ch-8-ordered mailing packets."
    ),
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:3000", "http://127.0.0.1:3000"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


