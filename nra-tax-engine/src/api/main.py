@app.post(
    "/api/v1/upload-and-process",
    response_model=TaxProcessResponse,
    tags=["tax"],
    deprecated=True,
)
async def upload_and_process_endpoint(
    i94_file: UploadFile = File(...),
    w2_files: List[UploadFile] = File(default=[]),
    form_1042s_files: List[UploadFile] = File(default=[]),
    mcq_answers_json: str = Form(...),
) -> TaxProcessResponse:
    """Legacy multipart endpoint preserved for the Phase-2 client.

    New clients should use ``POST /api/v1/submit`` with the typed
    :class:`SubmitRequest` body.
    """
    try:
        mcq_answers = json.loads(mcq_answers_json)
        parser = DocumentParser()

        i94_bytes = await i94_file.read()
        i94_ocr_text = parser.parse_file(i94_bytes, i94_file.filename or "i94.pdf")

        w2_ocr_texts = []
        for w2 in w2_files:
            w2_bytes = await w2.read()
            w2_ocr_texts.append(parser.parse_file(w2_bytes, w2.filename or "w2.pdf"))

        form_1042s_ocr_texts = []
        for f1042s in form_1042s_files:
            f1042s_bytes = await f1042s.read()
            form_1042s_ocr_texts.append(
                parser.parse_file(f1042s_bytes, f1042s.filename or "1042s.pdf")
            )

        engine = TaxEngine()
        _generated, final_state = engine.run_full_pipeline(
            i94_ocr_text=i94_ocr_text,
            w2_ocr_texts=w2_ocr_texts,
            form_1042s_ocr_texts=form_1042s_ocr_texts,
            mcq_answers=mcq_answers,
        )
    except Exception as exc:  # noqa: BLE001
        raise HTTPException(status_code=500, detail=str(exc)) from exc

    fica_total = (
        final_state.fica.incorrect_ss_withheld + final_state.fica.incorrect_medicare_withheld
    )
    return TaxProcessResponse(
        status="success",
        tax_year=final_state.tax_year,
        federal_refund_or_owed=float(final_state.tax.refund_or_owed),
        ny_refund_or_owed=float(final_state.ny.ny_refund_or_owed),
        fica_refund_amount=float(fica_total),
        forms_required=list(final_state.forms_required),
        completed_layers=list(final_state.completed_layers),
        generated_form_outputs=list(_generated),
        narrative_sections={},
    )


if __name__ == "__main__":
    uvicorn.run(app, host="0.0.0.0", port=8000)
