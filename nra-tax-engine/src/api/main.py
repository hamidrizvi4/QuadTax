class SubmitRequest(BaseModel):
    """Inputs to ``POST /api/v1/submit``."""

    intake: IntakePayload
    i94_ocr_text: str = ""
    w2_ocr_texts: List[str] = Field(default_factory=list)
    form_1042s_ocr_texts: List[str] = Field(default_factory=list)
    output_dir: str = Field(default="outputs", description="Directory to write packets into.")
    force_assembly: bool = Field(
        default=False,
        description=(
            "When True the engine bypasses the human-review gate. The caller "
            "is acknowledging every reason previously surfaced in "
            "``requires_human_review``. Default False — first request returns "
            "the review list without producing forms."
        ),
    )


@app.get("/api/v1/healthz", tags=["meta"])
def healthz() -> dict:
    return {"status": "ok"}


@app.post("/api/v1/submit", response_model=TaxProcessResponse, tags=["tax"])
def submit(request: SubmitRequest) -> TaxProcessResponse:
    """Run the full L1-L9 pipeline against a typed intake payload."""
    router = MCQRouter()
    mcq_dict = router.to_mcq_answers(request.intake)

    # Pre-seed identity so Phase-3 add-ons (AMT, ITIN, Form 2210) read the
    # right values when they run inside run_full_pipeline().
    seeded_state = router.populate_state(request.intake)

    engine = TaxEngine(force_assembly=request.force_assembly)
    try:
        generated_forms, state = engine.run_full_pipeline(
            i94_ocr_text=request.i94_ocr_text,
            w2_ocr_texts=request.w2_ocr_texts,
            form_1042s_ocr_texts=request.form_1042s_ocr_texts,
            mcq_answers=mcq_dict,
            initial_state=seeded_state,
        )
    except Exception as exc:  # noqa: BLE001
        logger.exception("Pipeline failure")
        raise HTTPException(status_code=500, detail=str(exc)) from exc

    # Build mailing packets from whatever the populator wrote into outputs/.
    packager = MailingPackager(tax_year=state.tax_year)
    package = packager.assemble(
        state,
        forms_dir=Path("outputs"),
        output_dir=Path(request.output_dir),
    )

    from src.narrative.generator import NarrativeGenerator
    narrative = NarrativeGenerator().generate_sections(state)

    fica_total = (
        state.fica.incorrect_ss_withheld + state.fica.incorrect_medicare_withheld
    )
    return TaxProcessResponse(
        status="success",
        tax_year=state.tax_year,
        federal_refund_or_owed=float(state.tax.refund_or_owed),
        ny_refund_or_owed=float(state.ny.ny_refund_or_owed),
        fica_refund_amount=float(fica_total),
        forms_required=list(state.forms_required),
        completed_layers=list(state.completed_layers),
        generated_form_outputs=list(generated_forms),
        federal_packet_path=package.federal.pdf_output or package.federal.json_output,
        ny_packet_path=(
            package.ny.pdf_output or package.ny.json_output if package.ny else None
        ),
        fica_packet_path=(
            package.fica_843.pdf_output or package.fica_843.json_output
            if package.fica_843
            else None
        ),
        requires_human_review=list(state.requires_human_review),
        narrative_sections=narrative,
    )


